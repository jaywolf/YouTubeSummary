import { describe, expect, it, vi } from "vitest";
import { DEFAULT_SETTINGS } from "../../src/domain/settings";
import type { ProviderClient } from "../../src/providers/types";
import { runSummaryPipeline } from "../../src/summarization/pipeline";

const video = {
  videoId: "aaaaaaaaaaa",
  canonicalUrl: "https://www.youtube.com/watch?v=aaaaaaaaaaa",
  title: "Video",
  channel: "Channel",
  durationSeconds: 20,
  captionTracks: []
};

const transcript = {
  track: {
    id: ".en",
    languageCode: "en",
    label: "English",
    isAutoGenerated: false,
    baseUrl: "https://www.youtube.com/api/timedtext?v=1"
  },
  segments: [{ startSeconds: 0, durationSeconds: 2, text: "Hello" }]
};

describe("runSummaryPipeline", () => {
  it("builds one final request, validates it, and attaches generation metadata", async () => {
    const provider: ProviderClient = {
      testConnection: vi.fn(async () => undefined),
      generate: vi.fn(async () => ({
        overview: ["Overview"],
        takeaways: [{ text: "Takeaway", startSeconds: 0 }],
        sections: [{ heading: "Start", startSeconds: 0, paragraphs: ["Details"] }]
      }))
    };
    const progress = vi.fn();

    await expect(runSummaryPipeline({
      transcript,
      video,
      settings: DEFAULT_SETTINGS,
      provider,
      onProgress: progress,
      signal: new AbortController().signal,
      now: () => new Date("2026-07-14T00:00:00.000Z")
    })).resolves.toEqual(expect.objectContaining({
      schemaVersion: 1,
      limitation: "Generated from captions.",
      generatedAt: "2026-07-14T00:00:00.000Z"
    }));
    expect(provider.generate).toHaveBeenCalledWith(
      expect.objectContaining({ kind: "final", schema: "video-summary" }),
      expect.any(Function),
      expect.any(AbortSignal)
    );
    expect(progress).toHaveBeenNthCalledWith(1, 0, 1);
    expect(progress).toHaveBeenLastCalledWith(1, 1);
  });

  it("rejects over-limit input before calling the provider", async () => {
    const provider: ProviderClient = {
      testConnection: vi.fn(async () => undefined),
      generate: vi.fn(async () => ({}))
    };
    await expect(runSummaryPipeline({
      transcript: {
        ...transcript,
        segments: [{ ...transcript.segments[0]!, text: "x".repeat(40_000) }]
      },
      video,
      settings: { ...DEFAULT_SETTINGS, contextWindowTokens: 8_192 },
      provider,
      onProgress: vi.fn(),
      signal: new AbortController().signal
    })).rejects.toMatchObject({ code: "context_limit_exceeded" });
    expect(provider.generate).not.toHaveBeenCalled();
  });

  it("honors cancellation before and after provider generation", async () => {
    const controller = new AbortController();
    const provider: ProviderClient = {
      testConnection: vi.fn(async () => undefined),
      generate: vi.fn(async () => {
        controller.abort();
        return {
          overview: ["Overview"],
          takeaways: [{ text: "Takeaway" }],
          sections: [{ heading: "Start", startSeconds: 0, paragraphs: ["Details"] }]
        };
      })
    };
    await expect(runSummaryPipeline({
      transcript,
      video,
      settings: DEFAULT_SETTINGS,
      provider,
      onProgress: vi.fn(),
      signal: controller.signal
    })).rejects.toMatchObject({ code: "request_canceled" });
  });

  it("maps an invalid provider result to the stable output-format error", async () => {
    const provider: ProviderClient = {
      testConnection: vi.fn(async () => undefined),
      generate: vi.fn(async () => ({ overview: ["Missing required fields"] }))
    };
    await expect(runSummaryPipeline({
      transcript,
      video,
      settings: DEFAULT_SETTINGS,
      provider,
      onProgress: vi.fn(),
      signal: new AbortController().signal
    })).rejects.toMatchObject({
      code: "provider_output_invalid",
      retryable: true,
      recoveryAction: "change_model"
    });
  });
});
