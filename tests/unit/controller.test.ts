import { describe, expect, it, vi } from "vitest";
import { AppError } from "../../src/domain/errors";
import { DEFAULT_SETTINGS, type ExtensionSettings } from "../../src/domain/settings";
import type { VideoSummary } from "../../src/domain/summary";
import type { Transcript, VideoContext } from "../../src/domain/video";
import type { ProviderClient } from "../../src/providers/types";
import {
  SummaryController,
  type SummaryControllerDependencies
} from "../../src/background/controller";

const contextA: VideoContext = {
    videoId: "aaaaaaaaaaa",
    canonicalUrl: "https://www.youtube.com/watch?v=aaaaaaaaaaa",
    title: "Video A",
    channel: "Channel",
    durationSeconds: 120,
    captionTracks: []
};
const contextB: VideoContext = {
    videoId: "bbbbbbbbbbb",
    canonicalUrl: "https://www.youtube.com/watch?v=bbbbbbbbbbb",
    title: "Video B",
    channel: "Channel",
    durationSeconds: 120,
    captionTracks: []
};

const transcript: Transcript = {
  track: {
    id: ".en",
    languageCode: "en",
    label: "English",
    isAutoGenerated: false,
    baseUrl: "https://www.youtube.com/api/timedtext?v=1"
  },
  segments: [{ startSeconds: 0, durationSeconds: 2, text: "Hello" }]
};

const summary: VideoSummary = {
  schemaVersion: 1,
  overview: ["Overview"],
  takeaways: [{ text: "Takeaway", startSeconds: 0 }],
  sections: [{ heading: "Start", startSeconds: 0, paragraphs: ["Details"] }],
  limitation: "Generated from captions.",
  generatedAt: "2026-07-14T00:00:00.000Z"
};

function configured(): ExtensionSettings {
  return {
    ...DEFAULT_SETTINGS,
    provider: { kind: "openai", apiKey: "synthetic", model: "test-model" }
  };
}

function deferred<T>() {
  let resolve!: (value: T) => void;
  let reject!: (reason?: unknown) => void;
  const promise = new Promise<T>((yes, no) => {
    resolve = yes;
    reject = no;
  });
  return { promise, resolve, reject };
}

function setup(overrides: Partial<SummaryControllerDependencies> = {}) {
  const events: unknown[] = [];
  const provider: ProviderClient = {
    testConnection: vi.fn(async () => undefined),
    generate: vi.fn(async () => ({
      overview: summary.overview,
      takeaways: summary.takeaways,
      sections: summary.sections
    }))
  };
  const dependencies: SummaryControllerDependencies = {
    getTab: vi.fn(async (tabId) => ({
      id: tabId,
      active: true,
      url: contextA.canonicalUrl
    })),
    readVideoContext: vi.fn(async () => contextA),
    loadSettings: vi.fn(async () => configured()),
    extractTranscript: vi.fn(async () => transcript),
    cancelTranscript: vi.fn(async () => undefined),
    createProvider: vi.fn(() => provider),
    runPipeline: vi.fn(async () => summary),
    emit: (event) => events.push(event),
    ...overrides
  };
  return { controller: new SummaryController(dependencies), dependencies, events, provider };
}

describe("SummaryController", () => {
  it("does not call a provider for unsupported pages, missing settings, or caption failures", async () => {
    const unsupported = setup({
      getTab: vi.fn(async (tabId) => ({ id: tabId, url: "https://www.youtube.com/" }))
    });
    await expect(unsupported.controller.start({ requestId: "unsupported", tabId: 4, force: false }))
      .resolves.toMatchObject({ state: "error", error: { code: "unsupported_page" } });
    expect(unsupported.dependencies.readVideoContext).not.toHaveBeenCalled();
    expect(unsupported.dependencies.createProvider).not.toHaveBeenCalled();

    const missing = setup({ loadSettings: vi.fn(async () => DEFAULT_SETTINGS) });
    await expect(missing.controller.start({ requestId: "missing", tabId: 4, force: false }))
      .resolves.toMatchObject({ state: "error", error: { code: "configuration_missing" } });
    expect(missing.dependencies.createProvider).not.toHaveBeenCalled();

    const captions = setup({
      extractTranscript: vi.fn(async () => {
        throw new AppError({
          code: "captions_unavailable",
          retryable: false,
          safeMessage: "No captions are available for this video.",
          recoveryAction: "none"
        });
      })
    });
    await expect(captions.controller.start({ requestId: "captions", tabId: 4, force: false }))
      .resolves.toMatchObject({ state: "error", error: { code: "captions_unavailable" } });
    expect(captions.dependencies.createProvider).not.toHaveBeenCalled();
  });

  it("requires the requested tab to still be active before reading page context", async () => {
    const fixture = setup({
      getTab: vi.fn(async (tabId) => ({ id: tabId, active: false, url: contextA.canonicalUrl }))
    });
    await expect(fixture.controller.start({ requestId: "inactive", tabId: 4, force: false }))
      .resolves.toMatchObject({ state: "error", error: { code: "unsupported_page" } });
    expect(fixture.dependencies.readVideoContext).not.toHaveBeenCalled();
    expect(fixture.dependencies.createProvider).not.toHaveBeenCalled();
  });

  it("cancels extraction explicitly and aborts every subsequent phase", async () => {
    const extraction = deferred<Transcript>();
    let extractionSignal!: AbortSignal;
    const fixture = setup({
      extractTranscript: vi.fn(async (_tabId, _requestId, _context, _preference, signal) => {
        extractionSignal = signal;
        return extraction.promise;
      })
    });

    const start = fixture.controller.start({ requestId: "cancel-me", tabId: 4, force: false });
    await vi.waitFor(() => expect(fixture.dependencies.extractTranscript).toHaveBeenCalledOnce());
    await fixture.controller.cancel(4, "cancel-me");
    expect(extractionSignal.aborted).toBe(true);
    expect(fixture.dependencies.cancelTranscript).toHaveBeenCalledWith(4, "cancel-me");
    extraction.resolve(transcript);

    await expect(start).resolves.toMatchObject({ state: "canceled" });
    expect(fixture.dependencies.createProvider).not.toHaveBeenCalled();
    expect(fixture.events).not.toContainEqual(expect.objectContaining({ type: "job/complete" }));
  });

  it("reserves start currentness before preflight awaits so a stalled A cannot replace B", async () => {
    const contextADeferred = deferred<VideoContext | null>();
    let contextCalls = 0;
    const fixture = setup({
      getTab: vi.fn(async (tabId) => ({
        id: tabId,
        active: true,
        url: contextCalls === 0 ? contextA.canonicalUrl : contextB.canonicalUrl
      })),
      readVideoContext: vi.fn(async () => {
        contextCalls++;
        return contextCalls === 1 ? contextADeferred.promise : contextB;
      })
    });

    const startA = fixture.controller.start({ requestId: "request-a", tabId: 4, force: false });
    await vi.waitFor(() => expect(fixture.dependencies.readVideoContext).toHaveBeenCalledTimes(1));
    const startB = fixture.controller.start({ requestId: "request-b", tabId: 4, force: true });
    await expect(startB).resolves.toMatchObject({
      requestId: "request-b",
      videoId: "bbbbbbbbbbb",
      state: "complete"
    });
    contextADeferred.resolve(contextA);
    await startA;

    expect(fixture.controller.status(4)).toMatchObject({
      requestId: "request-b",
      videoId: "bbbbbbbbbbb",
      state: "complete"
    });
    expect(fixture.events).not.toContainEqual(expect.objectContaining({
      type: "job/complete",
      requestId: "request-a"
    }));
  });

  it("does not let a late provider result overwrite a replacement job", async () => {
    const pipelineA = deferred<VideoSummary>();
    let pipelineCalls = 0;
    const fixture = setup({
      getTab: vi.fn(async (tabId) => ({ id: tabId, url: pipelineCalls === 0
        ? contextA.canonicalUrl
        : contextB.canonicalUrl, active: true })),
      readVideoContext: vi.fn(async () => pipelineCalls === 0 ? contextA : contextB),
      runPipeline: vi.fn(async () => {
        pipelineCalls++;
        return pipelineCalls === 1 ? pipelineA.promise : summary;
      })
    });

    const startA = fixture.controller.start({ requestId: "request-a", tabId: 4, force: false });
    await vi.waitFor(() => expect(fixture.dependencies.runPipeline).toHaveBeenCalledTimes(1));
    const startB = fixture.controller.start({ requestId: "request-b", tabId: 4, force: true });
    await expect(startB).resolves.toMatchObject({ requestId: "request-b", state: "complete" });
    pipelineA.resolve(summary);
    await startA;

    const completeEvents = fixture.events.filter((event) =>
      (event as { type?: string }).type === "job/complete");
    expect(completeEvents).toHaveLength(1);
    expect(completeEvents[0]).toMatchObject({ requestId: "request-b" });
  });

  it("cancels immediately while tab preflight is unresolved", async () => {
    const tab = deferred<{ id: number; active: boolean; url: string }>();
    const fixture = setup({ getTab: vi.fn(async () => tab.promise) });
    const start = fixture.controller.start({ requestId: "preflight", tabId: 4, force: false });
    await vi.waitFor(() => expect(fixture.dependencies.getTab).toHaveBeenCalledOnce());

    await expect(fixture.controller.cancel(4, "preflight")).resolves.toMatchObject({ state: "canceled" });
    tab.resolve({ id: 4, active: true, url: contextA.canonicalUrl });
    await expect(start).resolves.toMatchObject({ state: "canceled" });
    expect(fixture.dependencies.readVideoContext).not.toHaveBeenCalled();
    expect(fixture.dependencies.createProvider).not.toHaveBeenCalled();
  });

  it("does not cancel a same-video navigation during preflight and preserves completed jobs", async () => {
    const context = deferred<VideoContext | null>();
    const fixture = setup({ readVideoContext: vi.fn(async () => context.promise) });
    const start = fixture.controller.start({ requestId: "same-video", tabId: 4, force: false });
    await vi.waitFor(() => expect(fixture.dependencies.readVideoContext).toHaveBeenCalledOnce());

    await fixture.controller.navigated(4, "aaaaaaaaaaa");
    context.resolve(contextA);
    await expect(start).resolves.toMatchObject({ state: "complete" });
    await fixture.controller.navigated(4, "bbbbbbbbbbb");
    expect(fixture.controller.status(4)?.state).toBe("complete");
  });

  it("stores and emits the same validated completion payload", async () => {
    const fixture = setup();
    const completed = await fixture.controller.start({ requestId: "request-a", tabId: 4, force: false });
    const event = fixture.events.find((candidate) =>
      (candidate as { type?: string }).type === "job/complete") as { result: unknown };

    expect(completed).toMatchObject({ state: "complete", result: event.result });
    expect(fixture.controller.status(4)).toMatchObject({ state: "complete", result: event.result });
    expect((completed as { result: unknown }).result).toBe(event.result);
  });

  it("forwards phase-bearing progress and stores the actual final progress on completion", async () => {
    const fixture = setup({
      runPipeline: vi.fn(async (input) => {
        input.onProgress({ phase: "mapping", completed: 0, total: 4 });
        input.onProgress({ phase: "mapping", completed: 3, total: 4 });
        input.onProgress({ phase: "synthesizing", completed: 3, total: 4 });
        input.onProgress({ phase: "synthesizing", completed: 4, total: 4 });
        return summary;
      })
    });

    await expect(fixture.controller.start({ requestId: "long-job", tabId: 4, force: false }))
      .resolves.toMatchObject({
        state: "complete",
        progress: { phase: "synthesizing", completed: 4, total: 4 }
      });
    expect(fixture.events.filter((event) => (event as { type?: string }).type === "job/progress"))
      .toEqual([
        { type: "job/progress", requestId: "long-job", tabId: 4, phase: "mapping", completed: 0, total: 4 },
        { type: "job/progress", requestId: "long-job", tabId: 4, phase: "mapping", completed: 3, total: 4 },
        { type: "job/progress", requestId: "long-job", tabId: 4, phase: "synthesizing", completed: 3, total: 4 },
        { type: "job/progress", requestId: "long-job", tabId: 4, phase: "synthesizing", completed: 4, total: 4 }
      ]);
  });

  it("cancels an active mapping pipeline and suppresses its late result", async () => {
    const pipeline = deferred<VideoSummary>();
    let pipelineSignal!: AbortSignal;
    const fixture = setup({
      runPipeline: vi.fn(async (input) => {
        pipelineSignal = input.signal;
        input.onProgress({ phase: "mapping", completed: 1, total: 4 });
        return pipeline.promise;
      })
    });
    const start = fixture.controller.start({ requestId: "cancel-map", tabId: 4, force: false });
    await vi.waitFor(() => expect(fixture.dependencies.runPipeline).toHaveBeenCalledOnce());

    await expect(fixture.controller.cancel(4, "cancel-map")).resolves.toMatchObject({ state: "canceled" });
    expect(pipelineSignal.aborted).toBe(true);
    pipeline.resolve(summary);
    await expect(start).resolves.toMatchObject({ state: "canceled" });
    expect(fixture.events).not.toContainEqual(expect.objectContaining({ type: "job/complete" }));
  });

  it("cancels active synthesis after navigation and never exposes its late result", async () => {
    const pipeline = deferred<VideoSummary>();
    const fixture = setup({ runPipeline: vi.fn(async () => pipeline.promise) });
    const start = fixture.controller.start({ requestId: "navigate-map", tabId: 4, force: false });
    await vi.waitFor(() => expect(fixture.dependencies.runPipeline).toHaveBeenCalledOnce());

    await fixture.controller.navigated(4, "bbbbbbbbbbb");
    pipeline.resolve(summary);
    await expect(start).resolves.toMatchObject({ state: "canceled" });
    expect(fixture.controller.status(4)).toMatchObject({ state: "canceled" });
    expect(fixture.events).not.toContainEqual(expect.objectContaining({ type: "job/complete" }));
  });

  it("rejects invalid completion metadata before status or events expose a result", async () => {
    const fixture = setup({
      readVideoContext: vi.fn(async () => ({ ...contextA, title: "bad\u0000title" }))
    });

    await expect(fixture.controller.start({ requestId: "invalid", tabId: 4, force: false }))
      .resolves.toMatchObject({ state: "error", error: { code: "internal_error" } });
    expect(fixture.controller.status(4)).not.toHaveProperty("result");
    expect(fixture.events).not.toContainEqual(expect.objectContaining({ type: "job/complete" }));
  });

  it("keeps navigation cancellation authoritative even when the old content script disappears", async () => {
    const extraction = deferred<Transcript>();
    const fixture = setup({
      extractTranscript: vi.fn(async () => extraction.promise),
      cancelTranscript: vi.fn(async () => {
        throw new Error("Receiving end does not exist");
      })
    });
    const start = fixture.controller.start({ requestId: "navigate-away", tabId: 4, force: false });
    await vi.waitFor(() => expect(fixture.dependencies.extractTranscript).toHaveBeenCalledOnce());

    await expect(fixture.controller.navigated(4, "bbbbbbbbbbb")).resolves.toBeUndefined();
    extraction.reject(new Error("Receiving end does not exist"));
    await expect(start).resolves.toMatchObject({ state: "canceled" });
    expect(fixture.controller.status(4)).toMatchObject({ state: "canceled" });
    expect(fixture.events).not.toContainEqual(expect.objectContaining({ type: "job/error" }));
  });
});
