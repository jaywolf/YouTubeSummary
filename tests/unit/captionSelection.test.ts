import { describe, expect, it } from "vitest";
import type { CaptionTrack, TranscriptPreference } from "../../src/domain/video";
import { selectCaptionTrack } from "../../src/youtube/captionSelection";

const track = (
  id: string,
  languageCode: string,
  isAutoGenerated: boolean
): CaptionTrack => ({
  id,
  languageCode,
  label: id,
  isAutoGenerated,
  baseUrl: `https://www.youtube.com/api/timedtext?id=${id}`
});

describe("caption selection", () => {
  const preference: TranscriptPreference = {
    preferredLanguage: "es-MX",
    browserLanguage: "en-US"
  };

  it.each([
    {
      level: "human preferred-language",
      tracks: [track("auto-preferred", "es", true), track("human-preferred", "ES-es", false)],
      expected: "human-preferred"
    },
    {
      level: "automatic preferred-language",
      tracks: [track("human-browser", "en", false), track("auto-preferred", "es-419", true)],
      expected: "auto-preferred"
    },
    {
      level: "human browser-language",
      tracks: [track("auto-browser", "en-GB", true), track("human-browser", "EN", false)],
      expected: "human-browser"
    },
    {
      level: "automatic browser-language",
      tracks: [track("human-other", "fr", false), track("auto-browser", "en", true)],
      expected: "auto-browser"
    },
    {
      level: "remaining human",
      tracks: [track("auto-other", "de", true), track("human-other", "fr", false)],
      expected: "human-other"
    },
    {
      level: "remaining automatic",
      tracks: [track("auto-other", "de", true)],
      expected: "auto-other"
    }
  ])("selects the $level priority level", ({ tracks, expected }) => {
    expect(selectCaptionTrack(tracks, preference)?.id).toBe(expected);
  });

  it("skips preferred-language levels when no preference is configured", () => {
    const tracks = [track("human-es", "es", false), track("human-browser", "en", false)];

    expect(selectCaptionTrack(tracks, {
      preferredLanguage: null,
      browserLanguage: "en-US"
    })?.id).toBe("human-browser");
  });

  it("preserves source order as the final tie-breaker", () => {
    const tracks = [track("first", "es-ES", false), track("second", "es-MX", false)];

    expect(selectCaptionTrack(tracks, preference)?.id).toBe("first");
  });

  it("returns undefined when there are no tracks", () => {
    expect(selectCaptionTrack([], preference)).toBeUndefined();
  });
});
