import { beforeEach, describe, expect, it } from "vitest";
import {
  isAllowedCaptionUrl,
  readVideoContextFromTab,
  readPlayerSnapshotInPage,
  sanitizePlayerSnapshot
} from "../../src/youtube/playerSnapshot";
import { afterEach, vi } from "vitest";

function snapshotWithUrl(baseUrl: string): unknown {
  return {
    videoDetails: {
      videoId: "abcdefghijk",
      title: "A useful video",
      author: "Example channel",
      lengthSeconds: "123.5"
    },
    captions: {
      playerCaptionsTracklistRenderer: {
        captionTracks: [{
          baseUrl,
          languageCode: "en-US",
          name: { runs: [{ text: "English" }, { text: " (US)" }] },
          vssId: ".en",
          kind: "asr"
        }]
      }
    }
  };
}

describe("caption URL policy", () => {
  it.each([
    [false, "https://www.youtube.com/api/timedtext?v=1", true],
    [false, "http://127.0.0.1:43127/captions", false],
    [true, "http://127.0.0.1:43127/captions", true],
    [true, "http://localhost:43127/captions", false],
    [true, "http://192.0.2.2/captions", false],
    [true, "https://example.com/captions", false],
    [true, "https://youtube.com/captions", false],
    [true, "https://www.youtube.com.evil.example/captions", false]
  ])("testMode=%s allows %s: %s", (testMode, value, expected) => {
    expect(isAllowedCaptionUrl(new URL(value), testMode)).toBe(expected);
  });
});

describe("player snapshot sanitization", () => {
  it("maps trusted fields and strips all other page data", () => {
    const value = {
      ...(snapshotWithUrl("https://www.youtube.com/api/timedtext?v=1") as object),
      secret: "must not cross the boundary"
    };

    expect(sanitizePlayerSnapshot(value, false)).toEqual({
      videoId: "abcdefghijk",
      canonicalUrl: "https://www.youtube.com/watch?v=abcdefghijk",
      title: "A useful video",
      channel: "Example channel",
      durationSeconds: 123.5,
      captionTracks: [{
        id: ".en",
        languageCode: "en-US",
        label: "English (US)",
        isAutoGenerated: true,
        baseUrl: "https://www.youtube.com/api/timedtext?v=1"
      }]
    });
  });

  it.each([
    ["production loopback", "http://127.0.0.1:43127/captions", false],
    ["test localhost", "http://localhost:43127/captions", true],
    ["test external HTTP", "http://192.0.2.2/captions", true],
    ["test external HTTPS", "https://example.com/captions", true]
  ])("filters a %s URL", (_label, baseUrl, testMode) => {
    expect(sanitizePlayerSnapshot(snapshotWithUrl(baseUrl), testMode)?.captionTracks).toEqual([]);
  });

  it("accepts loopback only in trusted test mode", () => {
    expect(sanitizePlayerSnapshot(
      snapshotWithUrl("http://127.0.0.1:54321/captions"),
      true
    )?.captionTracks).toHaveLength(1);
  });

  it.each([
    null,
    {},
    { videoDetails: { videoId: "bad", title: "Title" } },
    { videoDetails: { videoId: "abcdefghijk", title: 4 } },
    { videoDetails: { videoId: "abcdefghijk", title: "Title", lengthSeconds: "Infinity" } }
  ])("rejects an invalid player snapshot %#", (value) => {
    expect(sanitizePlayerSnapshot(value, false)).toBeNull();
  });
});

describe("MAIN-world player reader", () => {
  beforeEach(() => {
    document.body.replaceChildren();
    delete (window as typeof window & { ytInitialPlayerResponse?: unknown }).ytInitialPlayerResponse;
    delete (window as typeof window & { ytplayer?: unknown }).ytplayer;
    history.replaceState({}, "", "/");
  });

  it("returns only video details and caption tracks", () => {
    history.replaceState({}, "", "/watch?v=abcdefghijk");
    const player = document.createElement("div") as HTMLDivElement & {
      getPlayerResponse: () => unknown;
    };
    player.id = "movie_player";
    player.getPlayerResponse = () => ({
      videoDetails: {
        videoId: "abcdefghijk",
        title: "Title",
        privateNestedData: "do not return"
      },
      captions: {
        playerCaptionsTracklistRenderer: {
          captionTracks: [{ languageCode: "en", privateTrackData: "do not return" }]
        }
      },
      privateData: "do not return"
    });
    document.body.append(player);

    expect(readPlayerSnapshotInPage()).toEqual({
      videoDetails: { videoId: "abcdefghijk", title: "Title" },
      captions: { playerCaptionsTracklistRenderer: { captionTracks: [{ languageCode: "en" }] } }
    });
  });

  it("does not call a non-function player bridge", () => {
    history.replaceState({}, "", "/watch?v=abcdefghijk");
    const player = document.createElement("div") as HTMLDivElement & { getPlayerResponse: unknown };
    player.id = "movie_player";
    player.getPlayerResponse = "not callable";
    document.body.append(player);

    expect(readPlayerSnapshotInPage()).toBeNull();
  });

  it("uses a matching initial player response when the player omits caption tracks", () => {
    history.replaceState({}, "", "/watch?v=abcdefghijk");
    const player = document.createElement("div") as HTMLDivElement & {
      getPlayerResponse: () => unknown;
    };
    player.id = "movie_player";
    player.getPlayerResponse = () => ({
      videoDetails: { videoId: "abcdefghijk", title: "Current title" }
    });
    document.body.append(player);
    (window as typeof window & { ytInitialPlayerResponse?: unknown }).ytInitialPlayerResponse = {
      videoDetails: { videoId: "abcdefghijk", title: "Initial title" },
      captions: {
        playerCaptionsTracklistRenderer: {
          captionTracks: [{
            baseUrl: "https://www.youtube.com/api/timedtext?v=abcdefghijk",
            languageCode: "en",
            name: { simpleText: "English" }
          }]
        }
      }
    };

    expect(readPlayerSnapshotInPage()).toEqual({
      videoDetails: { videoId: "abcdefghijk", title: "Current title" },
      captions: {
        playerCaptionsTracklistRenderer: {
          captionTracks: [{
            baseUrl: "https://www.youtube.com/api/timedtext?v=abcdefghijk",
            languageCode: "en",
            name: { simpleText: "English" }
          }]
        }
      }
    });
  });

  it("does not merge caption tracks from a stale SPA response", () => {
    history.replaceState({}, "", "/watch?v=abcdefghijk");
    const player = document.createElement("div") as HTMLDivElement & {
      getPlayerResponse: () => unknown;
    };
    player.id = "movie_player";
    player.getPlayerResponse = () => ({
      videoDetails: { videoId: "abcdefghijk", title: "Current title" }
    });
    document.body.append(player);
    (window as typeof window & { ytInitialPlayerResponse?: unknown }).ytInitialPlayerResponse = {
      ...(snapshotWithUrl("https://www.youtube.com/api/timedtext?v=bbbbbbbbbbb") as object),
      videoDetails: { videoId: "bbbbbbbbbbb", title: "Stale title" }
    };

    expect(readPlayerSnapshotInPage()).toEqual({
      videoDetails: { videoId: "abcdefghijk", title: "Current title" },
      captions: { playerCaptionsTracklistRenderer: { captionTracks: [] } }
    });
  });

  it("rejects a stale response after navigation leaves the watch page", () => {
    history.replaceState({}, "", "/feed/subscriptions");
    (window as typeof window & { ytInitialPlayerResponse?: unknown }).ytInitialPlayerResponse =
      snapshotWithUrl("https://www.youtube.com/api/timedtext?v=abcdefghijk");

    expect(readPlayerSnapshotInPage()).toBeNull();
  });

  it("falls through a malformed live caption track to a usable matching alternate", () => {
    history.replaceState({}, "", "/watch?v=abcdefghijk");
    const player = document.createElement("div") as HTMLDivElement & {
      getPlayerResponse: () => unknown;
    };
    player.id = "movie_player";
    player.getPlayerResponse = () => ({
      videoDetails: { videoId: "abcdefghijk", title: "Current title" },
      captions: {
        playerCaptionsTracklistRenderer: {
          captionTracks: [{ baseUrl: "not-a-url", languageCode: "en" }]
        }
      }
    });
    document.body.append(player);
    (window as typeof window & { ytInitialPlayerResponse?: unknown }).ytInitialPlayerResponse =
      snapshotWithUrl("https://www.youtube.com/api/timedtext?v=abcdefghijk");

    expect(readPlayerSnapshotInPage()).toMatchObject({
      videoDetails: { videoId: "abcdefghijk", title: "Current title" },
      captions: {
        playerCaptionsTracklistRenderer: {
          captionTracks: [{
            baseUrl: "https://www.youtube.com/api/timedtext?v=abcdefghijk",
            languageCode: "en-US"
          }]
        }
      }
    });
  });

  it("falls through unusable live details to valid same-video alternate details", () => {
    history.replaceState({}, "", "/watch?v=abcdefghijk");
    const player = document.createElement("div") as HTMLDivElement & {
      getPlayerResponse: () => unknown;
    };
    player.id = "movie_player";
    player.getPlayerResponse = () => ({
      videoDetails: { videoId: "abcdefghijk", title: 42 }
    });
    document.body.append(player);
    (window as typeof window & { ytInitialPlayerResponse?: unknown }).ytInitialPlayerResponse =
      snapshotWithUrl("https://www.youtube.com/api/timedtext?v=abcdefghijk");

    expect(readPlayerSnapshotInPage()).toMatchObject({
      videoDetails: {
        videoId: "abcdefghijk",
        title: "A useful video",
        author: "Example channel",
        lengthSeconds: "123.5"
      }
    });
  });

  it("uses a raw configured response when the live player bridge throws", () => {
    history.replaceState({}, "", "/watch?v=abcdefghijk");
    const player = document.createElement("div") as HTMLDivElement & {
      getPlayerResponse: () => unknown;
    };
    player.id = "movie_player";
    player.getPlayerResponse = () => {
      throw new Error("Player is not ready");
    };
    document.body.append(player);
    (window as typeof window & { ytplayer?: unknown }).ytplayer = {
      config: {
        args: {
          raw_player_response: JSON.stringify(snapshotWithUrl(
            "https://www.youtube.com/api/timedtext?v=abcdefghijk"
          ))
        }
      }
    };

    expect(readPlayerSnapshotInPage()).toMatchObject({
      videoDetails: { videoId: "abcdefghijk", title: "A useful video" },
      captions: {
        playerCaptionsTracklistRenderer: {
          captionTracks: [{ languageCode: "en-US" }]
        }
      }
    });
  });
});

describe("background snapshot bridge", () => {
  afterEach(() => {
    vi.unstubAllGlobals();
  });

  it("executes only the self-contained reader in MAIN world for the requested tab", async () => {
    const executeScript = vi.fn(async () => [{
      frameId: 0,
      result: snapshotWithUrl("https://www.youtube.com/api/timedtext?v=1")
    }]);
    vi.stubGlobal("browser", { scripting: { executeScript } });

    await expect(readVideoContextFromTab(23)).resolves.toMatchObject({
      videoId: "abcdefghijk",
      captionTracks: [{ baseUrl: "https://www.youtube.com/api/timedtext?v=1" }]
    });
    expect(executeScript).toHaveBeenCalledWith({
      target: { tabId: 23 },
      world: "MAIN",
      func: readPlayerSnapshotInPage
    });
  });

  it("returns null when the bridge yields no valid result", async () => {
    vi.stubGlobal("browser", {
      scripting: { executeScript: vi.fn(async () => [{ frameId: 0, result: null }]) }
    });

    await expect(readVideoContextFromTab(23)).resolves.toBeNull();
  });
});
