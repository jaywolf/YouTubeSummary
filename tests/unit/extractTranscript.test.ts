import { describe, expect, it, vi } from "vitest";
import { AppError } from "../../src/domain/errors";
import type {
  CaptionTrack,
  TranscriptPreference,
  TranscriptSegment,
  VideoContext
} from "../../src/domain/video";
import { extractTranscript } from "../../src/youtube/extractTranscript";

const track: CaptionTrack = {
  id: "human-en",
  languageCode: "en",
  label: "English",
  isAutoGenerated: false,
  baseUrl: "https://www.youtube.com/api/timedtext?v=1"
};

const context: VideoContext = {
  videoId: "abcdefghijk",
  canonicalUrl: "https://www.youtube.com/watch?v=abcdefghijk",
  title: "Video",
  channel: null,
  durationSeconds: 10,
  captionTracks: [track]
};

const preference: TranscriptPreference = {
  preferredLanguage: "en",
  browserLanguage: "en-US"
};

const visibleSegments: TranscriptSegment[] = [
  { startSeconds: 0, durationSeconds: 2, text: "Visible fallback" }
];

describe("transcript extraction coordinator", () => {
  it("fetches, parses, and normalizes the selected timed-text track first", async () => {
    const controller = new AbortController();
    const fetchText = vi.fn(async () =>
      `<transcript><text start="0" dur="2"> Primary  text </text></transcript>`
    );
    const readVisibleSegments = vi.fn(() => visibleSegments);

    await expect(extractTranscript(
      context,
      preference,
      { fetchText, readVisibleSegments },
      controller.signal
    )).resolves.toEqual({
      track,
      segments: [{ startSeconds: 0, durationSeconds: 2, text: "Primary text" }]
    });
    expect(fetchText).toHaveBeenCalledWith(track.baseUrl, controller.signal);
    expect(readVisibleSegments).not.toHaveBeenCalled();
  });

  it.each([
    ["no snapshot tracks", { ...context, captionTracks: [] }, null],
    ["empty timed text", context, "<transcript></transcript>"],
    ["malformed timed text", context, "<transcript><text></transcript>"]
  ])("uses the visible DOM fallback for %s", async (_label, input, xml) => {
    const fetchText = vi.fn(async () => xml ?? "unused");

    await expect(extractTranscript(
      input,
      preference,
      { fetchText, readVisibleSegments: () => visibleSegments },
      new AbortController().signal
    )).resolves.toMatchObject({
      track: {
        id: "visible-transcript",
        languageCode: "en",
        label: "Visible transcript",
        isAutoGenerated: false,
        baseUrl: ""
      },
      segments: visibleSegments
    });
    expect(fetchText).toHaveBeenCalledTimes(input.captionTracks.length === 0 ? 0 : 1);
  });

  it("uses the browser language for a visible transcript when no preference is configured", async () => {
    const transcript = await extractTranscript(
      { ...context, captionTracks: [] },
      { preferredLanguage: null, browserLanguage: "fr-CA" },
      { fetchText: vi.fn(), readVisibleSegments: () => visibleSegments },
      new AbortController().signal
    );

    expect(transcript.track.languageCode).toBe("fr-CA");
  });

  it("throws captions_unavailable when neither source has transcript segments", async () => {
    await expect(extractTranscript(
      { ...context, captionTracks: [] },
      preference,
      { fetchText: vi.fn(), readVisibleSegments: () => [] },
      new AbortController().signal
    )).rejects.toMatchObject({ code: "captions_unavailable", retryable: false });
  });

  it("uses the visible DOM fallback when an advertised caption fetch fails", async () => {
    const readVisibleSegments = vi.fn(() => visibleSegments);

    await expect(extractTranscript(
      context,
      preference,
      {
        fetchText: async () => { throw new Error("private upstream response"); },
        readVisibleSegments
      },
      new AbortController().signal
    )).resolves.toMatchObject({
      track: {
        id: "visible-transcript",
        languageCode: "en",
        label: "Visible transcript",
        isAutoGenerated: false,
        baseUrl: ""
      },
      segments: visibleSegments
    });
    expect(readVisibleSegments).toHaveBeenCalledOnce();
  });

  it("wraps caption fetch failures when the visible DOM fallback is empty", async () => {
    const failure = extractTranscript(
      context,
      preference,
      {
        fetchText: async () => { throw new Error("private upstream response"); },
        readVisibleSegments: () => []
      },
      new AbortController().signal
    );

    await expect(failure).rejects.toBeInstanceOf(AppError);
    await expect(failure).rejects.toMatchObject({
      code: "transcript_extraction_failed",
      retryable: true,
      safeMessage: "The transcript could not be extracted.",
      recoveryAction: "retry"
    });
  });

  it("wraps caption fetch failures when the visible DOM fallback is unavailable", async () => {
    await expect(extractTranscript(
      context,
      preference,
      {
        fetchText: async () => { throw new Error("private upstream response"); },
        readVisibleSegments: () => { throw new Error("DOM changed"); }
      },
      new AbortController().signal
    )).rejects.toMatchObject({
      code: "transcript_extraction_failed",
      retryable: true,
      safeMessage: "The transcript could not be extracted.",
      recoveryAction: "retry"
    });
  });

  it("preserves abort failures so runtime cancellation can classify them", async () => {
    const abortError = new DOMException("Aborted", "AbortError");

    await expect(extractTranscript(
      context,
      preference,
      { fetchText: async () => { throw abortError; }, readVisibleSegments: () => [] },
      new AbortController().signal
    )).rejects.toBe(abortError);
  });

  it("wraps visible bridge failures as transcript_extraction_failed", async () => {
    await expect(extractTranscript(
      { ...context, captionTracks: [] },
      preference,
      {
        fetchText: vi.fn(),
        readVisibleSegments: () => { throw new Error("DOM changed"); }
      },
      new AbortController().signal
    )).rejects.toMatchObject({ code: "transcript_extraction_failed" });
  });
});
