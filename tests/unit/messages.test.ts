import { describe, expect, it } from "vitest";
import {
  APP_ERROR_CODES,
  ERROR_PRESENTATIONS,
  RECOVERY_ACTIONS,
  type AppErrorCode,
  type RecoveryAction
} from "../../src/domain/errors";
import {
  parseAppMessage,
  parseTranscriptResponse,
  type BackgroundEvent
} from "../../src/domain/messages";

describe("background progress serialization", () => {
  it("round-trips an explicit pipeline phase without intermediate model text", () => {
    const event = {
      type: "job/progress",
      requestId: "request-1",
      tabId: 7,
      phase: "reducing",
      completed: 3,
      total: 6
    } satisfies BackgroundEvent;

    expect(JSON.parse(JSON.stringify(event))).toEqual(event);
    expect(event).not.toHaveProperty("text");
    expect(event).not.toHaveProperty("summary");
  });
});

describe("parseAppMessage", () => {
  it("accepts a typed panel request", () => {
    expect(parseAppMessage({
      type: "panel/start",
      requestId: "request-1",
      tabId: 7,
      expectedVideoId: "aaaaaaaaaaa",
      force: false
    }).type).toBe("panel/start");
  });

  it("requires the expected video identity on panel start", () => {
    expect(() => parseAppMessage({
      type: "panel/start",
      requestId: "request-1",
      tabId: 7,
      force: false
    })).toThrow();
  });

  it("rejects a message without a request identifier", () => {
    expect(() => parseAppMessage({ type: "panel/cancel", tabId: 7 })).toThrow();
  });

  it("validates a complete YouTube extraction request", () => {
    expect(parseAppMessage({
      type: "youtube/extract",
      requestId: "extract-1",
      tabId: 7,
      context: {
        videoId: "abcdefghijk",
        canonicalUrl: "https://www.youtube.com/watch?v=abcdefghijk",
        title: "Video",
        channel: null,
        durationSeconds: 12,
        captionTracks: [{
          id: "en",
          languageCode: "en",
          label: "English",
          isAutoGenerated: false,
          baseUrl: "https://www.youtube.com/api/timedtext?v=1"
        }]
      },
      preference: { preferredLanguage: null, browserLanguage: "en-US" }
    }).type).toBe("youtube/extract");
  });

  it("validates an explicit extraction cancellation without an AbortSignal", () => {
    expect(parseAppMessage({
      type: "youtube/cancel-extract",
      requestId: "extract-1",
      tabId: 7
    }).type).toBe("youtube/cancel-extract");
  });

  it("requires the expected video identity on seek messages", () => {
    expect(parseAppMessage({
      type: "youtube/seek",
      requestId: "seek-1",
      tabId: 7,
      videoId: "abcdefghijk",
      seconds: 12
    })).toMatchObject({ type: "youtube/seek", videoId: "abcdefghijk" });
    expect(() => parseAppMessage({
      type: "youtube/seek",
      requestId: "seek-1",
      tabId: 7,
      seconds: 12
    })).toThrow();
  });

  it("rejects non-finite seek positions", () => {
    expect(() => parseAppMessage({
      type: "youtube/seek",
      requestId: "seek-infinity",
      tabId: 7,
      videoId: "abcdefghijk",
      seconds: Number.POSITIVE_INFINITY
    })).toThrow();
  });

  it("rejects invalid nested extraction context", () => {
    expect(() => parseAppMessage({
      type: "youtube/extract",
      requestId: "extract-1",
      tabId: 7,
      context: { videoId: "bad" },
      preference: { preferredLanguage: null, browserLanguage: "en-US" }
    })).toThrow();
  });
});

describe("parseTranscriptResponse", () => {
  it("accepts a plain validated transcript", () => {
    expect(parseTranscriptResponse({
      track: {
        id: "en",
        languageCode: "en",
        label: "English",
        isAutoGenerated: false,
        baseUrl: "https://www.youtube.com/api/timedtext?v=1"
      },
      segments: [{ startSeconds: 0, durationSeconds: 2, text: "Hello" }]
    })).toHaveProperty("segments.0.text", "Hello");
  });

  it("accepts only safe error fields", () => {
    expect(parseTranscriptResponse({
      code: "captions_unavailable",
      retryable: false,
      safeMessage: "No captions are available for this video.",
      recoveryAction: "none"
    })).toHaveProperty("code", "captions_unavailable");
  });

  it("accepts every shared application error code at runtime", () => {
    const typedCodes: readonly AppErrorCode[] = APP_ERROR_CODES;

    expect(typedCodes).toHaveLength(new Set(typedCodes).size);
    for (const code of typedCodes) {
      expect(parseTranscriptResponse({
        code,
        retryable: false,
        safeMessage: "Safe message",
        recoveryAction: "none"
      })).toHaveProperty("code", code);
    }
  });

  it("keeps error presentations synchronized with the shared codes", () => {
    expect(Object.keys(ERROR_PRESENTATIONS).sort()).toEqual([...APP_ERROR_CODES].sort());
  });

  it("uses transcript-oriented extraction error wording", () => {
    expect(ERROR_PRESENTATIONS.captions_unavailable).toEqual({
      title: "No transcript available",
      message: "YouTube does not provide captions or a transcript for this video.",
      actions: []
    });
    expect(ERROR_PRESENTATIONS.transcript_extraction_failed).toEqual({
      title: "Transcript could not be read",
      message: "The extension could not open or read YouTube's transcript. Reload the video and retry.",
      actions: ["retry"]
    });
  });

  it("rejects an error code outside the shared tuple", () => {
    expect(() => parseTranscriptResponse({
      code: "not_an_application_error",
      retryable: false,
      safeMessage: "Safe message",
      recoveryAction: "none"
    })).toThrow();
  });

  it("accepts every shared recovery action at runtime", () => {
    const typedActions: readonly RecoveryAction[] = RECOVERY_ACTIONS;

    expect(typedActions).toEqual(["retry", "settings", "change_model", "none"]);
    expect(typedActions).toHaveLength(new Set(typedActions).size);
    for (const recoveryAction of typedActions) {
      expect(parseTranscriptResponse({
        code: "internal_error",
        retryable: recoveryAction === "retry",
        safeMessage: "Safe message",
        recoveryAction
      })).toHaveProperty("recoveryAction", recoveryAction);
    }
  });

  it("rejects a recovery action outside the shared tuple", () => {
    expect(() => parseTranscriptResponse({
      code: "internal_error",
      retryable: false,
      safeMessage: "Safe message",
      recoveryAction: "reload"
    })).toThrow();
  });

  it("rejects invalid transcript timing", () => {
    expect(() => parseTranscriptResponse({
      track: {
        id: "en",
        languageCode: "en",
        label: "English",
        isAutoGenerated: false,
        baseUrl: ""
      },
      segments: [{ startSeconds: -1, durationSeconds: 2, text: "Bad" }]
    })).toThrow();
  });
});
