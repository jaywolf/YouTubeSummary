import { describe, expect, it } from "vitest";
import {
  SUMMARY_LIMITATION,
  chunkSummarySchema,
  completedSummaryPayloadSchema,
  summaryContentSchema,
  videoSummarySchema
} from "../../src/domain/summary";

const content = {
  overview: ["A grounded overview."],
  takeaways: [{ text: "A key point", startSeconds: 12 }],
  sections: [{ heading: "Opening", startSeconds: 0, paragraphs: ["Details."] }]
};

const summary = {
  schemaVersion: 1 as const,
  ...content,
  limitation: SUMMARY_LIMITATION,
  generatedAt: "2026-07-13T12:00:00.000Z"
};

describe("summary schemas", () => {
  it("accepts HTML-shaped text as data and rejects control characters", () => {
    expect(videoSummarySchema.parse(summary)).toEqual(summary);
    expect(videoSummarySchema.parse({
      ...summary,
      overview: ["<img onerror=alert(1)>"]
    }).overview[0]).toBe("<img onerror=alert(1)>");
    expect(() => videoSummarySchema.parse({
      ...summary,
      overview: ["invalid\u0000text"]
    })).toThrow();
  });

  it("enforces summary collection, timestamp, and string limits", () => {
    expect(() => summaryContentSchema.parse({ ...content, overview: [] })).toThrow();
    expect(() => summaryContentSchema.parse({
      ...content,
      takeaways: Array.from({ length: 13 }, (_, index) => ({ text: `Point ${index}` }))
    })).toThrow();
    expect(() => summaryContentSchema.parse({
      ...content,
      sections: [{ heading: "Opening", startSeconds: Number.POSITIVE_INFINITY, paragraphs: ["Details."] }]
    })).toThrow();
    expect(() => summaryContentSchema.parse({
      ...content,
      sections: [{ heading: "x".repeat(301), startSeconds: 0, paragraphs: ["Details."] }]
    })).toThrow();
  });

  it("validates chunk summaries independently from final summaries", () => {
    const chunk = {
      facts: [{ text: "The speaker introduces the topic.", startSeconds: 0 }],
      sectionStarts: [{ heading: "Introduction", startSeconds: 0 }]
    };
    expect(chunkSummarySchema.parse(chunk)).toEqual(chunk);
    expect(() => chunkSummarySchema.parse({ ...chunk, facts: [] })).toThrow();
  });

  it("validates the complete payload delivered to the panel", () => {
    const payload = {
      video: { videoId: "abcdefghijk", title: "A video", channel: null },
      caption: { languageCode: "en", label: "English", isAutoGenerated: false },
      summary,
      cache: { key: "cache-key", createdAt: "2026-07-13T12:00:00.000Z" }
    };
    expect(completedSummaryPayloadSchema.parse(payload)).toEqual(payload);
    expect(() => completedSummaryPayloadSchema.parse({
      ...payload,
      video: { ...payload.video, videoId: "bad" }
    })).toThrow();
    expect(() => completedSummaryPayloadSchema.parse({
      ...payload,
      cache: { ...payload.cache, createdAt: "not-a-date" }
    })).toThrow();
  });
});
