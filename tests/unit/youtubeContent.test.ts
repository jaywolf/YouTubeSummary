import { describe, expect, it, vi } from "vitest";
import type { AppMessage } from "../../src/domain/messages";
import type { Transcript, VideoContext } from "../../src/domain/video";
import {
  createChromeMessageListener,
  createYouTubeMessageHandler,
  sendYouTubeNavigation
} from "../../src/youtube/contentRuntime";

const context: VideoContext = {
  videoId: "abcdefghijk",
  canonicalUrl: "https://www.youtube.com/watch?v=abcdefghijk",
  title: "Video",
  channel: null,
  durationSeconds: 10,
  captionTracks: []
};

const extractMessage: AppMessage = {
  type: "youtube/extract",
  requestId: "extract-1",
  tabId: 7,
  context,
  preference: { preferredLanguage: null, browserLanguage: "en-US" }
};

const transcript: Transcript = {
  track: {
    id: "visible-transcript",
    languageCode: "en-US",
    label: "Visible transcript",
    isAutoGenerated: false,
    baseUrl: ""
  },
  segments: [{ startSeconds: 0, durationSeconds: 1, text: "Hello" }]
};

describe("YouTube content runtime messages", () => {
  it("validates extraction input and returns a validated plain transcript", async () => {
    const extract = vi.fn(async () => transcript);
    const handler = createYouTubeMessageHandler({
      extract,
      fetchText: vi.fn(),
      readVisibleSegments: vi.fn(),
      findVideo: () => null
    });

    await expect(handler(extractMessage)).resolves.toEqual(transcript);
    expect(extract).toHaveBeenCalledOnce();
  });

  it("ignores an invalid incoming message before dispatch", async () => {
    const extract = vi.fn(async () => transcript);
    const handler = createYouTubeMessageHandler({
      extract,
      fetchText: vi.fn(),
      readVisibleSegments: vi.fn(),
      findVideo: () => null
    });

    await expect(handler({ type: "youtube/extract" })).resolves.toBeUndefined();
    expect(extract).not.toHaveBeenCalled();
  });

  it("aborts and removes the controller through youtube/cancel-extract", async () => {
    let extractionSignal: AbortSignal | undefined;
    const handler = createYouTubeMessageHandler({
      extract: async (_context, _preference, _dependencies, signal) => {
        extractionSignal = signal;
        return await new Promise<Transcript>((_resolve, reject) => {
          signal.addEventListener("abort", () => {
            reject(new DOMException("Aborted", "AbortError"));
          }, { once: true });
        });
      },
      fetchText: vi.fn(),
      readVisibleSegments: vi.fn(),
      findVideo: () => null
    });

    const extraction = handler(extractMessage);
    await handler({ type: "youtube/cancel-extract", requestId: "extract-1", tabId: 7 });

    expect(extractionSignal?.aborted).toBe(true);
    await expect(extraction).resolves.toMatchObject({
      code: "request_canceled",
      retryable: false,
      recoveryAction: "none"
    });
  });

  it("seeks without forcing a paused video to play", async () => {
    const video = document.createElement("video");
    const play = vi.spyOn(video, "play");
    const handler = createYouTubeMessageHandler({
      extract: vi.fn(),
      fetchText: vi.fn(),
      readVisibleSegments: vi.fn(),
      findVideo: () => video
    });

    await handler({
      type: "youtube/seek",
      requestId: "seek-1",
      tabId: 7,
      seconds: 42
    });

    expect(video.currentTime).toBe(42);
    expect(play).not.toHaveBeenCalled();
  });

  it("returns a safe extraction error and omits its cause", async () => {
    const handler = createYouTubeMessageHandler({
      extract: async () => { throw new Error("private DOM details"); },
      fetchText: vi.fn(),
      readVisibleSegments: vi.fn(),
      findVideo: () => null
    });

    await expect(handler(extractMessage)).resolves.toEqual({
      code: "internal_error",
      retryable: true,
      safeMessage: "The transcript could not be extracted.",
      recoveryAction: "retry"
    });
  });
});

describe("YouTube SPA navigation", () => {
  it.each([
    ["https://www.youtube.com/watch?v=abcdefghijk", "abcdefghijk"],
    ["https://www.youtube.com/feed/subscriptions", null]
  ])("sends the parsed video identity for %s", async (url, expectedVideoId) => {
    const sendMessage = vi.fn(async () => undefined);

    await sendYouTubeNavigation(url, "navigation-1", sendMessage);

    expect(sendMessage).toHaveBeenCalledWith({
      type: "youtube/navigated",
      requestId: "navigation-1",
      tabId: 0,
      videoId: expectedVideoId
    });
  });
});

describe("Chrome 114 runtime listener adapter", () => {
  it("returns literal true and responds exactly once after recognized work settles", async () => {
    let resolveHandler: ((value: Transcript) => void) | undefined;
    const handler = vi.fn(() => new Promise<Transcript>((resolve) => {
      resolveHandler = resolve;
    }));
    const sendResponse = vi.fn();
    const listener = createChromeMessageListener(handler);

    const returned = listener(extractMessage, {}, sendResponse);

    expect(returned).toBe(true);
    expect(sendResponse).not.toHaveBeenCalled();
    resolveHandler?.(transcript);
    await vi.waitFor(() => expect(sendResponse).toHaveBeenCalledOnce());
    expect(sendResponse).toHaveBeenCalledWith(transcript);
  });

  it.each([
    { type: "youtube/cancel-extract", requestId: "extract-1", tabId: 7 },
    { type: "youtube/seek", requestId: "seek-1", tabId: 7, seconds: 4 }
  ])("keeps the channel open for recognized $type work", async (message) => {
    const handler = vi.fn(async () => undefined);
    const sendResponse = vi.fn();
    const listener = createChromeMessageListener(handler);

    expect(listener(message, {}, sendResponse)).toBe(true);
    await vi.waitFor(() => expect(sendResponse).toHaveBeenCalledOnce());
    expect(handler).toHaveBeenCalledWith(message);
  });

  it.each([
    ["invalid", { type: "youtube/extract" }],
    ["panel message", { type: "panel/status", requestId: "status-1", tabId: 7 }],
    ["navigation notice", {
      type: "youtube/navigated",
      requestId: "navigation-1",
      tabId: 0,
      videoId: "abcdefghijk"
    }]
  ])("does not claim an unrelated or %s message", (_label, message) => {
    const handler = vi.fn(async () => transcript);
    const sendResponse = vi.fn();
    const listener = createChromeMessageListener(handler);

    expect(listener(message, {}, sendResponse)).toBeUndefined();
    expect(handler).not.toHaveBeenCalled();
    expect(sendResponse).not.toHaveBeenCalled();
  });

  it("converts an unexpected handler rejection to one safe internal-error response", async () => {
    const handler = vi.fn(async () => { throw new Error("private rejection details"); });
    const sendResponse = vi.fn();
    const listener = createChromeMessageListener(handler);

    expect(listener(extractMessage, {}, sendResponse)).toBe(true);
    await vi.waitFor(() => expect(sendResponse).toHaveBeenCalledOnce());
    expect(sendResponse).toHaveBeenCalledWith({
      code: "internal_error",
      retryable: true,
      safeMessage: "The transcript could not be extracted.",
      recoveryAction: "retry"
    });
  });
});
