import { afterAll, beforeAll, describe, expect, it, vi } from "vitest";

const rawSnapshot = {
  videoDetails: {
    videoId: "abcdefghijk",
    title: "Video",
    author: "Channel",
    lengthSeconds: "12"
  },
  captions: {
    playerCaptionsTracklistRenderer: {
      captionTracks: [{
        baseUrl: "https://www.youtube.com/api/timedtext?v=1",
        languageCode: "en",
        name: { simpleText: "English" },
        vssId: ".en"
      }]
    }
  }
};

const transcript = {
  track: {
    id: ".en",
    languageCode: "en",
    label: "English",
    isAutoGenerated: false,
    baseUrl: "https://www.youtube.com/api/timedtext?v=1"
  },
  segments: [{ startSeconds: 0, durationSeconds: 1, text: "Hello" }]
};

describe("background transcript bridge", () => {
  let background: Record<string, (...args: never[]) => Promise<unknown>>;
  let installedListener: (() => unknown) | undefined;
  const executeScript = vi.fn(async () => [{ frameId: 0, result: rawSnapshot }]);
  const sendMessage = vi.fn<() => Promise<unknown>>(async () => transcript);
  const localSetAccessLevel = vi.fn(async () => undefined);
  const sessionSetAccessLevel = vi.fn(async () => undefined);
  const setPanelBehavior = vi.fn(async () => undefined);

  beforeAll(async () => {
    vi.stubGlobal("defineBackground", (callback: unknown) => callback);
    vi.stubGlobal("browser", {
      scripting: { executeScript },
      tabs: { sendMessage },
      runtime: {
        onInstalled: {
          addListener: vi.fn((listener: () => unknown) => {
            installedListener = listener;
          })
        }
      },
      storage: {
        local: { setAccessLevel: localSetAccessLevel },
        session: { setAccessLevel: sessionSetAccessLevel }
      },
      sidePanel: { setPanelBehavior }
    });
    background = await import("../../entrypoints/background") as unknown as typeof background;
  });

  afterAll(() => {
    vi.unstubAllGlobals();
  });

  it("reads and sanitizes MAIN-world data before sending youtube/extract", async () => {
    await expect(background.extractTranscriptFromTab?.(
      9 as never,
      "request-1" as never,
      { preferredLanguage: null, browserLanguage: "en-US" } as never
    )).resolves.toEqual({
      context: expect.objectContaining({ videoId: "abcdefghijk" }),
      transcript
    });

    expect(sendMessage).toHaveBeenCalledWith(9, expect.objectContaining({
      type: "youtube/extract",
      requestId: "request-1",
      tabId: 9,
      context: expect.objectContaining({ videoId: "abcdefghijk" })
    }));
  });

  it("enforces trusted storage on every startup and configures the panel idempotently", async () => {
    const definition = (background as unknown as { default: () => void | Promise<void> }).default;
    await definition();

    expect(localSetAccessLevel).toHaveBeenCalledOnce();
    expect(localSetAccessLevel).toHaveBeenCalledWith({ accessLevel: "TRUSTED_CONTEXTS" });
    expect(sessionSetAccessLevel).toHaveBeenCalledOnce();
    expect(sessionSetAccessLevel).toHaveBeenCalledWith({ accessLevel: "TRUSTED_CONTEXTS" });
    expect(setPanelBehavior).toHaveBeenCalledOnce();

    await installedListener?.();
    expect(setPanelBehavior).toHaveBeenCalledTimes(2);
    expect(localSetAccessLevel).toHaveBeenCalledOnce();
    expect(sessionSetAccessLevel).toHaveBeenCalledOnce();
  });

  it("forwards explicit serializable cancellation", async () => {
    await background.cancelTranscriptExtraction?.(9 as never, "request-1" as never);

    expect(sendMessage).toHaveBeenCalledWith(9, {
      type: "youtube/cancel-extract",
      requestId: "request-1",
      tabId: 9
    });
  });

  it("maps a MAIN-world execution failure to a safe extraction error", async () => {
    executeScript.mockRejectedValueOnce(new Error("private page failure"));

    await expect(background.extractTranscriptFromTab?.(
      9 as never,
      "request-2" as never,
      { preferredLanguage: null, browserLanguage: "en-US" } as never
    )).rejects.toMatchObject({
      code: "transcript_extraction_failed",
      safeMessage: "The transcript could not be extracted."
    });
  });

  it("maps an invalid content-script response to a safe extraction error", async () => {
    sendMessage.mockResolvedValueOnce({ privateData: "invalid response" });

    await expect(background.extractTranscriptFromTab?.(
      9 as never,
      "request-3" as never,
      { preferredLanguage: null, browserLanguage: "en-US" } as never
    )).rejects.toMatchObject({
      code: "transcript_extraction_failed",
      safeMessage: "The transcript could not be extracted."
    });
  });
});
