import { afterAll, beforeAll, describe, expect, it, vi } from "vitest";

const rawSnapshot = {
  videoDetails: {
    videoId: "abcdefghijk",
    title: "Video",
    author: "Channel",
    lengthSeconds: "12"
  },
  captions: {
    playerCaptionsTracklistRenderer: {
      captionTracks: [{
        baseUrl: "https://www.youtube.com/api/timedtext?v=1",
        languageCode: "en",
        name: { simpleText: "English" },
        vssId: ".en"
      }]
    }
  }
};

const transcript = {
  track: {
    id: ".en",
    languageCode: "en",
    label: "English",
    isAutoGenerated: false,
    baseUrl: "https://www.youtube.com/api/timedtext?v=1"
  },
  segments: [{ startSeconds: 0, durationSeconds: 1, text: "Hello" }]
};

describe("background transcript bridge", () => {
  let background: typeof import("../../entrypoints/background");
  let installedListener: (() => unknown) | undefined;
  const executeScript = vi.fn<(
    input?: unknown
  ) => Promise<Array<{ frameId: number; result: unknown }>>>(
    async () => [{ frameId: 0, result: rawSnapshot }]
  );
  const sendMessage = vi.fn<() => Promise<unknown>>(async () => transcript);
  const localSetAccessLevel = vi.fn(async () => undefined);
  const sessionSetAccessLevel = vi.fn(async () => undefined);
  const sessionGet = vi.fn(async () => ({}));
  const sessionSet = vi.fn(async () => undefined);
  const setPanelBehavior = vi.fn(async () => undefined);

  beforeAll(async () => {
    vi.stubGlobal("defineBackground", (callback: unknown) => callback);
    vi.stubGlobal("browser", {
      scripting: { executeScript },
      tabs: { sendMessage },
      runtime: {
        id: "extension-id",
        onMessage: { addListener: vi.fn() },
        onConnect: { addListener: vi.fn() },
        onInstalled: {
          addListener: vi.fn((listener: () => unknown) => {
            installedListener = listener;
          })
        }
      },
      storage: {
        local: { setAccessLevel: localSetAccessLevel },
        session: {
          setAccessLevel: sessionSetAccessLevel,
          get: sessionGet,
          set: sessionSet
        }
      },
      sidePanel: { setPanelBehavior }
    });
    background = await import("../../entrypoints/background");
  });

  afterAll(() => {
    vi.unstubAllGlobals();
  });

  it("reads and sanitizes MAIN-world data before sending youtube/extract", async () => {
    await expect(background.extractTranscriptFromTab(
      9,
      "request-1",
      { preferredLanguage: null, browserLanguage: "en-US" }
    )).resolves.toEqual({
      context: expect.objectContaining({ videoId: "abcdefghijk" }),
      transcript
    });

    expect(sendMessage).toHaveBeenCalledWith(9, expect.objectContaining({
      type: "youtube/extract",
      requestId: "request-1",
      tabId: 9,
      context: expect.objectContaining({ videoId: "abcdefghijk" })
    }));
  });

  it("enforces trusted storage on every startup and configures the panel idempotently", async () => {
    const consoleError = vi.spyOn(console, "error").mockImplementation(() => undefined);
    const definition = (background as unknown as { default: () => void | Promise<void> }).default;
    await definition();

    expect(localSetAccessLevel).toHaveBeenCalledOnce();
    expect(localSetAccessLevel).toHaveBeenCalledWith({ accessLevel: "TRUSTED_CONTEXTS" });
    expect(sessionSetAccessLevel).toHaveBeenCalledOnce();
    expect(sessionSetAccessLevel).toHaveBeenCalledWith({ accessLevel: "TRUSTED_CONTEXTS" });
    expect(setPanelBehavior).toHaveBeenCalledOnce();
    await vi.waitFor(() => expect(sessionSet).toHaveBeenCalledWith({
      "activeJobs.v1": { version: 1, jobs: [] }
    }));
    expect(sessionGet).toHaveBeenCalledWith("activeJobs.v1");
    expect(consoleError).not.toHaveBeenCalled();

    await installedListener?.();
    expect(setPanelBehavior).toHaveBeenCalledTimes(2);
    expect(localSetAccessLevel).toHaveBeenCalledOnce();
    expect(sessionSetAccessLevel).toHaveBeenCalledOnce();
    consoleError.mockRestore();
  });

  it("forwards explicit serializable cancellation", async () => {
    await background.cancelTranscriptExtraction(9, "request-1");

    expect(sendMessage).toHaveBeenCalledWith(9, {
      type: "youtube/cancel-extract",
      requestId: "request-1",
      tabId: 9
    });
  });

  it("maps a MAIN-world execution failure to a safe extraction error", async () => {
    executeScript.mockRejectedValueOnce(new Error("private page failure"));

    await expect(background.extractTranscriptFromTab(
      9,
      "request-2",
      { preferredLanguage: null, browserLanguage: "en-US" }
    )).rejects.toMatchObject({
      code: "transcript_extraction_failed",
      safeMessage: "The transcript could not be extracted."
    });
  });

  it("maps a missing sanitized video context to a safe context error", async () => {
    executeScript.mockResolvedValueOnce([{ frameId: 0, result: null }]);

    await expect(background.extractTranscriptFromTab(
      9,
      "request-no-context",
      { preferredLanguage: null, browserLanguage: "en-US" }
    )).rejects.toMatchObject({
      code: "video_context_unavailable",
      retryable: true,
      recoveryAction: "retry",
      safeMessage: "The video context could not be read."
    });
    expect(sendMessage).not.toHaveBeenCalledWith(9, expect.objectContaining({
      requestId: "request-no-context"
    }));
  });

  it("maps an invalid content-script response to a safe extraction error", async () => {
    sendMessage.mockResolvedValueOnce({ privateData: "invalid response" });

    await expect(background.extractTranscriptFromTab(
      9,
      "request-3",
      { preferredLanguage: null, browserLanguage: "en-US" }
    )).rejects.toMatchObject({
      code: "transcript_extraction_failed",
      safeMessage: "The transcript could not be extracted."
    });
  });

  it("preserves a structured content-script error and retry metadata", async () => {
    sendMessage.mockResolvedValueOnce({
      code: "rate_limited",
      retryable: true,
      safeMessage: "The provider is busy.",
      recoveryAction: "retry",
      retryAfterSeconds: 7
    });

    await expect(background.extractTranscriptWithContext(
      9,
      "request-safe-error",
      {
        videoId: "abcdefghijk",
        canonicalUrl: "https://www.youtube.com/watch?v=abcdefghijk",
        title: "Video",
        channel: "Channel",
        durationSeconds: 12,
        captionTracks: [transcript.track]
      },
      { preferredLanguage: null, browserLanguage: "en-US" }
    )).rejects.toMatchObject({
      code: "rate_limited",
      retryable: true,
      recoveryAction: "retry",
      retryAfterSeconds: 7
    });
  });

  it("stops awaiting the content bridge when the controller aborts", async () => {
    sendMessage.mockImplementationOnce(() => new Promise((resolve) => {
      setTimeout(() => resolve(transcript), 25);
    }));
    const controller = new AbortController();
    const pending = background.extractTranscriptWithContext(
      9,
      "request-abort",
      {
        videoId: "abcdefghijk",
        canonicalUrl: "https://www.youtube.com/watch?v=abcdefghijk",
        title: "Video",
        channel: "Channel",
        durationSeconds: 12,
        captionTracks: [transcript.track]
      },
      { preferredLanguage: null, browserLanguage: "en-US" },
      controller.signal
    );

    controller.abort();

    await expect(pending).rejects.toBe(controller.signal.reason);
  });
});
