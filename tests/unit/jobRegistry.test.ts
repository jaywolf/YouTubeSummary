import { describe, expect, it } from "vitest";
import { JobRegistry } from "../../src/background/jobRegistry";

const result = {
  video: { videoId: "bbbbbbbbbbb", title: "Video B", channel: "Channel" },
  caption: { languageCode: "en", label: "English", isAutoGenerated: false },
  summary: {
    schemaVersion: 1 as const,
    overview: ["Overview"],
    takeaways: [{ text: "Takeaway", startSeconds: 12 }],
    sections: [{ heading: "Start", startSeconds: 0, paragraphs: ["Details"] }],
    limitation: "Generated from captions." as const,
    generatedAt: "2026-07-14T00:00:00.000Z"
  },
  cache: null
};

describe("JobRegistry", () => {
  it("aborts a replaced job and lets only the current identity complete", () => {
    const ids = ["request-a", "request-b"];
    const registry = new JobRegistry(() => ids.shift()!);
    const jobA = registry.begin(4, "aaaaaaaaaaa");
    const jobB = registry.begin(4, "bbbbbbbbbbb");

    expect(jobA.signal.aborted).toBe(true);
    expect(registry.isCurrent(jobA)).toBe(false);
    expect(registry.isCurrent(jobB)).toBe(true);
    expect(registry.complete(jobA, result)).toBe(false);
    expect(registry.complete(jobB, result)).toBe(true);
    expect(registry.status(4)).toEqual(expect.objectContaining({
      requestId: "request-b",
      videoId: "bbbbbbbbbbb",
      state: "complete",
      result
    }));
  });

  it("requires matching request and video identity for all mutations", () => {
    const registry = new JobRegistry(() => "request-a");
    registry.begin(4, "aaaaaaaaaaa");

    expect(registry.transition({ requestId: "other", tabId: 4, videoId: "aaaaaaaaaaa" }, "summarizing"))
      .toBe(false);
    expect(registry.fail(
      { requestId: "request-a", tabId: 4, videoId: "bbbbbbbbbbb" },
      {
        code: "internal_error",
        retryable: true,
        safeMessage: "Safe error.",
        recoveryAction: "retry"
      }
    )).toBe(false);
    expect(registry.status(4)?.state).toBe("loading_video");
  });

  it("returns serializable discriminated snapshots without controllers", () => {
    const registry = new JobRegistry(() => "request-a", () => 1234);
    const job = registry.begin(4, "aaaaaaaaaaa");
    registry.progress(job, 0, 1);

    const snapshot = registry.status(4);
    expect(snapshot).toEqual({
      requestId: "request-a",
      tabId: 4,
      videoId: "aaaaaaaaaaa",
      state: "loading_video",
      progress: { completed: 0, total: 1 },
      startedAt: 1234
    });
    expect(snapshot).not.toHaveProperty("controller");
    expect(snapshot).not.toHaveProperty("signal");
    expect(JSON.parse(JSON.stringify(snapshot))).toEqual(snapshot);
  });

  it("cancels idempotently and never exposes a result outside complete", () => {
    const registry = new JobRegistry(() => "request-a");
    const job = registry.begin(4, "aaaaaaaaaaa");
    let aborts = 0;
    job.signal.addEventListener("abort", () => aborts++);

    expect(registry.cancel(4, "request-a")).toBe(true);
    expect(registry.cancel(4, "request-a")).toBe(false);
    expect(aborts).toBe(1);
    expect(registry.status(4)).toEqual(expect.objectContaining({ state: "canceled" }));
    expect(registry.status(4)).not.toHaveProperty("result");
  });

  it("rejects malformed completion payloads before they enter status", () => {
    const registry = new JobRegistry(() => "request-a");
    const job = registry.begin(4, "aaaaaaaaaaa");

    expect(() => registry.complete(job, {
      ...result,
      video: { ...result.video, videoId: "wrong" }
    })).toThrow();
    expect(registry.status(4)?.state).toBe("loading_video");
  });

  it("does not turn terminal completed or failed jobs into canceled jobs", () => {
    const completeRegistry = new JobRegistry(() => "complete");
    const completed = completeRegistry.begin(4, "bbbbbbbbbbb");
    expect(completeRegistry.complete(completed, result)).toBe(true);
    expect(completeRegistry.cancel(4, "complete")).toBe(false);
    expect(completeRegistry.fail(completed, {
      code: "internal_error",
      retryable: true,
      safeMessage: "Late failure.",
      recoveryAction: "retry"
    })).toBe(false);
    expect(completeRegistry.status(4)?.state).toBe("complete");

    const failedRegistry = new JobRegistry(() => "failed");
    const failed = failedRegistry.begin(4, "aaaaaaaaaaa");
    failedRegistry.fail(failed, {
      code: "internal_error",
      retryable: true,
      safeMessage: "Safe error.",
      recoveryAction: "retry"
    });
    expect(failedRegistry.cancel(4, "failed")).toBe(false);
    expect(failedRegistry.status(4)?.state).toBe("error");
  });
});
