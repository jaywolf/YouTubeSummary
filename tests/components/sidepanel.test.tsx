import { StrictMode } from "react";
import { act, render, screen } from "@testing-library/react";
import userEvent from "@testing-library/user-event";
import { afterEach, describe, expect, it, vi } from "vitest";
import { App, type PanelClient, type PanelPort } from "../../entrypoints/sidepanel/App";
import type { BackgroundEvent } from "../../src/domain/messages";
import type { JobSnapshot } from "../../src/background/jobRegistry";

const result = {
  video: { videoId: "aaaaaaaaaaa", title: "Hostile video", channel: "Channel" },
  caption: { languageCode: "en", label: "English", isAutoGenerated: false },
  summary: {
    schemaVersion: 1 as const,
    overview: ["<img src=x onerror=alert(1)>", "A second overview."],
    takeaways: [{ text: "Important point", startSeconds: 12 }],
    sections: [{
      heading: "Main story",
      startSeconds: 754,
      paragraphs: ["The detailed section."]
    }],
    limitation: "Generated from captions." as const,
    generatedAt: "2026-07-14T00:00:00.000Z"
  },
  cache: null
};

const complete: JobSnapshot = {
  requestId: "job-complete",
  tabId: 4,
  videoId: "aaaaaaaaaaa",
  state: "complete",
  progress: { phase: "synthesizing", completed: 1, total: 1 },
  startedAt: 1,
  result
};

function deferred<T>() {
  let resolve!: (value: T | PromiseLike<T>) => void;
  let reject!: (reason?: unknown) => void;
  const promise = new Promise<T>((yes, no) => {
    resolve = yes;
    reject = no;
  });
  return { promise, resolve, reject };
}

function fakePort() {
  const listeners = new Set<(event: BackgroundEvent) => void>();
  return {
    name: "summary-panel",
    disconnect: vi.fn(),
    onMessage: {
      addListener: vi.fn((listener: (event: BackgroundEvent) => void) => listeners.add(listener)),
      removeListener: vi.fn((listener: (event: BackgroundEvent) => void) => listeners.delete(listener))
    },
    emit(event: BackgroundEvent) {
      listeners.forEach((listener) => listener(event));
    }
  } satisfies PanelPort & { emit(event: BackgroundEvent): void };
}

function setup(status: JobSnapshot | null = null) {
  const port = fakePort();
  const ids = ["status-query", "auto-start", "regenerate", "retry"];
  const sendRuntimeMessage = vi.fn(async (message: { type: string; requestId: string }) => {
    if (message.type === "panel/status") return status;
    if (message.type === "panel/start") {
      return {
        requestId: message.requestId,
        tabId: 4,
        videoId: "aaaaaaaaaaa",
        state: "summarizing",
        progress: { phase: "synthesizing", completed: 0, total: 1 },
        startedAt: 2
      } satisfies JobSnapshot;
    }
    return {
      requestId: message.requestId,
      tabId: 4,
      videoId: "aaaaaaaaaaa",
      state: "canceled",
      progress: null,
      startedAt: 2
    } satisfies JobSnapshot;
  });
  const client: PanelClient = {
    queryActiveTab: vi.fn(async () => ({
      id: 4,
      active: true,
      url: "https://www.youtube.com/watch?v=aaaaaaaaaaa"
    })),
    getTab: vi.fn(async () => ({
      id: 4,
      active: true,
      url: "https://www.youtube.com/watch?v=aaaaaaaaaaa"
    })),
    sendRuntimeMessage,
    sendTabMessage: vi.fn(async () => undefined),
    connect: vi.fn(() => port),
    openOptionsPage: vi.fn(async () => undefined),
    writeClipboard: vi.fn(async () => undefined),
    createRequestId: vi.fn(() => ids.shift()!)
  };
  return { client, port, sendRuntimeMessage };
}

afterEach(() => {
  vi.restoreAllMocks();
});

describe("side panel", () => {
  it("auto-starts once under React StrictMode when no current job exists", async () => {
    const fixture = setup(null);
    render(<StrictMode><App client={fixture.client} /></StrictMode>);

    await screen.findByText("Creating final summary");
    expect(fixture.sendRuntimeMessage.mock.calls.filter(([message]) =>
      message.type === "panel/status")).toHaveLength(1);
    expect(fixture.sendRuntimeMessage.mock.calls.filter(([message]) =>
      message.type === "panel/start")).toHaveLength(1);
    expect(fixture.sendRuntimeMessage).toHaveBeenCalledWith({
      type: "panel/start",
      requestId: "auto-start",
      tabId: 4,
      force: false
    });
  });

  it("renders unsupported and configuration-required states with the right action", async () => {
    const unsupported = setup();
    unsupported.client.queryActiveTab = vi.fn(async () => ({ id: 4, url: "https://www.youtube.com/" }));
    const { unmount } = render(<App client={unsupported.client} />);
    expect(await screen.findByText("Open a standard YouTube video page to create a summary.")).toBeTruthy();
    expect(unsupported.sendRuntimeMessage).not.toHaveBeenCalled();
    unmount();

    const configuration = setup({
      requestId: "configuration",
      tabId: 4,
      videoId: "aaaaaaaaaaa",
      state: "error",
      progress: null,
      startedAt: 1,
      error: {
        code: "configuration_missing",
        retryable: true,
        safeMessage: "Choose a provider, model, and API key in settings.",
        recoveryAction: "settings"
      }
    });
    render(<App client={configuration.client} />);
    await userEvent.click(await screen.findByRole("button", { name: "Open settings" }));
    expect(configuration.client.openOptionsPage).toHaveBeenCalledOnce();
    expect(configuration.sendRuntimeMessage.mock.calls.filter(([message]) =>
      message.type === "panel/start")).toHaveLength(0);
  });

  it("filters port events by both active tab and current request", async () => {
    const fixture = setup({
      requestId: "current-job",
      tabId: 4,
      videoId: "aaaaaaaaaaa",
      state: "summarizing",
      progress: { phase: "synthesizing", completed: 0, total: 1 },
      startedAt: 1
    });
    render(<App client={fixture.client} />);
    await screen.findByText("Creating final summary");
    expect(fixture.sendRuntimeMessage.mock.calls.filter(([message]) =>
      message.type === "panel/start")).toHaveLength(0);

    fixture.port.emit({ type: "job/complete", requestId: "current-job", tabId: 8, result });
    fixture.port.emit({ type: "job/complete", requestId: "stale-job", tabId: 4, result });
    expect(screen.queryByText("Hostile video")).toBeNull();
    fixture.port.emit({ type: "job/complete", requestId: "current-job", tabId: 4, result });
    expect(await screen.findByText("Hostile video")).toBeTruthy();
  });

  it("shows phase-correct chunk and synthesis copy without intermediate model text", async () => {
    const fixture = setup({
      requestId: "chunk-job",
      tabId: 4,
      videoId: "aaaaaaaaaaa",
      state: "summarizing",
      progress: { phase: "mapping", completed: 1, total: 4 },
      startedAt: 1
    });
    render(<App client={fixture.client} />);
    expect(await screen.findByText("Chunk 2 of 3")).toBeTruthy();
    expect(screen.getByText("Summarizing caption chunks")).toBeTruthy();

    await act(async () => fixture.port.emit({
        type: "job/progress",
        requestId: "chunk-job",
        tabId: 4,
        phase: "not-a-phase",
        completed: 2,
        total: 4
      } as unknown as BackgroundEvent));
    expect(screen.getByText("Summarizing caption chunks")).toBeTruthy();
    expect(screen.getByText("Chunk 2 of 3")).toBeTruthy();

    fixture.port.emit({
      type: "job/progress",
      requestId: "chunk-job",
      tabId: 4,
      phase: "reducing",
      completed: 3,
      total: 6,
      intermediateText: "SECRET INTERMEDIATE"
    } as BackgroundEvent);
    expect(await screen.findByText("Combining chunk summaries")).toBeTruthy();
    expect(screen.getByText("Synthesis 4 of 6")).toBeTruthy();
    expect(screen.queryByText("SECRET INTERMEDIATE")).toBeNull();

    fixture.port.emit({
      type: "job/progress",
      requestId: "chunk-job",
      tabId: 4,
      phase: "synthesizing",
      completed: 5,
      total: 6
    });
    expect(await screen.findByText("Creating final summary")).toBeTruthy();
    expect(screen.getByText("Synthesis 6 of 6")).toBeTruthy();
  });

  it("does not let a late start response overwrite a faster completion event", async () => {
    let resolveStart!: (snapshot: JobSnapshot | null) => void;
    const fixture = setup(null);
    fixture.client.sendRuntimeMessage = vi.fn(async (message) => {
      if (message.type === "panel/status") return null;
      return new Promise((resolve) => { resolveStart = resolve; });
    });
    render(<App client={fixture.client} />);
    await vi.waitFor(() => expect(resolveStart).toBeTypeOf("function"));
    fixture.port.emit({ type: "job/complete", requestId: "auto-start", tabId: 4, result });
    expect(await screen.findByText("Hostile video")).toBeTruthy();
    resolveStart({
      requestId: "auto-start",
      tabId: 4,
      videoId: "aaaaaaaaaaa",
      state: "summarizing",
      progress: null,
      startedAt: 1
    });
    await Promise.resolve();
    expect(screen.getByText("Hostile video")).toBeTruthy();
  });

  it("reconciles a terminal port event that arrives after stale status is captured", async () => {
    let resolveStatus!: (snapshot: JobSnapshot | null) => void;
    const fixture = setup(null);
    fixture.client.sendRuntimeMessage = vi.fn(async (message) => {
      if (message.type === "panel/status") {
        return new Promise((resolve) => { resolveStatus = resolve; });
      }
      return null;
    });
    render(<App client={fixture.client} />);
    await vi.waitFor(() => expect(resolveStatus).toBeTypeOf("function"));

    fixture.port.emit({
      type: "job/complete",
      requestId: "other-job",
      tabId: 4,
      result
    });
    fixture.port.emit({
      type: "job/complete",
      requestId: "current-job",
      tabId: 4,
      result: {
        ...result,
        video: { ...result.video, videoId: "bbbbbbbbbbb", title: "Wrong buffered video" }
      }
    });
    fixture.port.emit({
      type: "job/complete",
      requestId: "current-job",
      tabId: 4,
      result
    });
    resolveStatus({
      requestId: "current-job",
      tabId: 4,
      videoId: "aaaaaaaaaaa",
      state: "summarizing",
      progress: { phase: "synthesizing", completed: 0, total: 1 },
      startedAt: 1
    });

    expect(await screen.findByText("Hostile video")).toBeTruthy();
    expect(screen.queryByText("Wrong buffered video")).toBeNull();
    expect((fixture.client.sendRuntimeMessage as ReturnType<typeof vi.fn>).mock.calls.filter(
      ([message]) => message.type === "panel/start"
    )).toHaveLength(0);
  });

  it("cancels an active job and regenerates a completed one with force", async () => {
    const active = setup({
      requestId: "active-job",
      tabId: 4,
      videoId: "aaaaaaaaaaa",
      state: "extracting_transcript",
      progress: null,
      startedAt: 1
    });
    const { unmount } = render(<App client={active.client} />);
    await userEvent.click(await screen.findByRole("button", { name: "Cancel" }));
    expect(active.sendRuntimeMessage).toHaveBeenCalledWith({
      type: "panel/cancel",
      requestId: "active-job",
      tabId: 4
    });
    unmount();

    const completed = setup(complete);
    render(<App client={completed.client} />);
    await userEvent.click(await screen.findByRole("button", { name: "Regenerate" }));
    expect(completed.sendRuntimeMessage).toHaveBeenCalledWith({
      type: "panel/start",
      requestId: "auto-start",
      tabId: 4,
      force: true
    });
  });

  it.each(["canceled", "interrupted"] as const)(
    "does not auto-start a current %s snapshot",
    async (state) => {
      const fixture = setup({
        requestId: `job-${state}`,
        tabId: 4,
        videoId: "aaaaaaaaaaa",
        state,
        progress: null,
        startedAt: 1
      });
      render(<App client={fixture.client} />);
      await screen.findByRole("button", { name: "Retry" });
      expect(fixture.sendRuntimeMessage.mock.calls.filter(([message]) =>
        message.type === "panel/start")).toHaveLength(0);
    }
  );

  it("does not render a completed snapshot for another video and starts the active video", async () => {
    const otherResult = {
      ...result,
      video: { ...result.video, videoId: "bbbbbbbbbbb", title: "Wrong video" }
    };
    const fixture = setup({
      ...complete,
      videoId: "bbbbbbbbbbb",
      result: otherResult
    });
    render(<App client={fixture.client} />);
    await screen.findByText("Creating final summary");
    expect(screen.queryByText("Wrong video")).toBeNull();
    expect(fixture.sendRuntimeMessage).toHaveBeenCalledWith(expect.objectContaining({
      type: "panel/start",
      force: false,
      tabId: 4
    }));
  });

  it("disconnects without canceling and re-queries status after remount", async () => {
    const fixture = setup(complete);
    const rendered = render(<App client={fixture.client} />);
    await screen.findByText("Hostile video");
    rendered.unmount();
    expect(fixture.port.onMessage.removeListener).toHaveBeenCalled();
    expect(fixture.port.disconnect).toHaveBeenCalled();
    expect(fixture.sendRuntimeMessage.mock.calls.filter(([message]) =>
      message.type === "panel/cancel")).toHaveLength(0);

    render(<App client={fixture.client} />);
    await screen.findByText("Hostile video");
    expect(fixture.sendRuntimeMessage.mock.calls.filter(([message]) =>
      message.type === "panel/status")).toHaveLength(2);
  });

  it("ignores a late status from an unmounted panel while a remount shows newer state", async () => {
    const fixture = setup(complete);
    let resolveOldStatus!: (snapshot: JobSnapshot | null) => void;
    let statusCalls = 0;
    fixture.client.sendRuntimeMessage = vi.fn(async (message) => {
      if (message.type !== "panel/status") return null;
      statusCalls++;
      if (statusCalls === 1) {
        return new Promise((resolve) => { resolveOldStatus = resolve; });
      }
      return complete;
    });
    const first = render(<App client={fixture.client} />);
    await vi.waitFor(() => expect(resolveOldStatus).toBeTypeOf("function"));
    first.unmount();

    render(<App client={fixture.client} />);
    expect(await screen.findByText("Hostile video")).toBeTruthy();
    resolveOldStatus(null);
    await Promise.resolve();
    expect(screen.getByText("Hostile video")).toBeTruthy();
    expect((fixture.client.sendRuntimeMessage as ReturnType<typeof vi.fn>).mock.calls.filter(
      ([message]) => message.type === "panel/start"
    )).toHaveLength(0);
  });

  it("renders hostile strings literally and copies only structured plain text", async () => {
    const fixture = setup(complete);
    render(<App client={fixture.client} />);

    expect(await screen.findByText("<img src=x onerror=alert(1)>")).toBeTruthy();
    expect(fixture.sendRuntimeMessage.mock.calls.filter(([message]) =>
      message.type === "panel/start")).toHaveLength(0);
    expect(document.querySelector("img")).toBeNull();
    await userEvent.click(screen.getByRole("button", { name: "Copy" }));
    expect(fixture.client.writeClipboard).toHaveBeenCalledOnce();
    const copied = String((fixture.client.writeClipboard as ReturnType<typeof vi.fn>).mock.calls[0]![0]);
    expect(copied).toContain("Hostile video");
    expect(copied).toContain("<img src=x onerror=alert(1)>");
    expect(copied).not.toContain("<section");
  });

  it("keeps Copy available and handles clipboard rejection", async () => {
    const fixture = setup(complete);
    fixture.client.writeClipboard = vi.fn(async () => {
      throw new Error("Clipboard permission denied");
    });
    render(<App client={fixture.client} />);

    await userEvent.click(await screen.findByRole("button", { name: "Copy" }));
    await vi.waitFor(() => expect(fixture.client.writeClipboard).toHaveBeenCalledOnce());
    expect(screen.getByRole("button", { name: "Copy" })).toBeTruthy();
    expect(screen.queryByRole("button", { name: "Copied" })).toBeNull();
  });

  it("clears copied acknowledgement for regeneration until the new summary is copied", async () => {
    const fixture = setup(complete);
    render(<App client={fixture.client} />);
    await userEvent.click(await screen.findByRole("button", { name: "Copy" }));
    expect(await screen.findByRole("button", { name: "Copied" })).toBeTruthy();

    await userEvent.click(screen.getByRole("button", { name: "Regenerate" }));
    await screen.findByText("Creating final summary");
    fixture.port.emit({ type: "job/complete", requestId: "auto-start", tabId: 4, result });
    expect(await screen.findByRole("button", { name: "Copy" })).toBeTruthy();

    await userEvent.click(screen.getByRole("button", { name: "Copy" }));
    expect(await screen.findByRole("button", { name: "Copied" })).toBeTruthy();
  });

  it("keeps the latest successful copy acknowledged when an older attempt rejects", async () => {
    const older = deferred<void>();
    const newer = deferred<void>();
    const fixture = setup(complete);
    fixture.client.writeClipboard = vi.fn()
      .mockImplementationOnce(() => older.promise)
      .mockImplementationOnce(() => newer.promise);
    render(<App client={fixture.client} />);
    const copy = await screen.findByRole("button", { name: "Copy" });
    await userEvent.click(copy);
    await userEvent.click(copy);

    await act(async () => newer.resolve());
    expect(await screen.findByRole("button", { name: "Copied" })).toBeTruthy();
    await act(async () => older.reject(new Error("older rejection")));
    expect(screen.getByRole("button", { name: "Copied" })).toBeTruthy();
  });

  it("does not let an older fulfillment override a newer failed copy attempt", async () => {
    const older = deferred<void>();
    const fixture = setup(complete);
    fixture.client.writeClipboard = vi.fn()
      .mockImplementationOnce(() => older.promise)
      .mockRejectedValueOnce(new Error("newer rejection"));
    render(<App client={fixture.client} />);
    const copy = await screen.findByRole("button", { name: "Copy" });
    await userEvent.click(copy);
    await userEvent.click(copy);
    expect(screen.getByRole("button", { name: "Copy" })).toBeTruthy();

    await act(async () => older.resolve());
    expect(screen.getByRole("button", { name: "Copy" })).toBeTruthy();
  });

  it("does not let a copy fulfillment from the old request acknowledge a new summary", async () => {
    const oldCopy = deferred<void>();
    const fixture = setup(complete);
    fixture.client.writeClipboard = vi.fn(() => oldCopy.promise);
    render(<App client={fixture.client} />);
    await userEvent.click(await screen.findByRole("button", { name: "Copy" }));
    await userEvent.click(screen.getByRole("button", { name: "Regenerate" }));
    await screen.findByText("Creating final summary");
    fixture.port.emit({ type: "job/complete", requestId: "auto-start", tabId: 4, result });
    expect(await screen.findByRole("button", { name: "Copy" })).toBeTruthy();

    await act(async () => oldCopy.resolve());
    expect(screen.getByRole("button", { name: "Copy" })).toBeTruthy();
  });

  it("seeks only the tab that still displays the result video", async () => {
    const fixture = setup(complete);
    render(<App client={fixture.client} />);
    await userEvent.click(await screen.findByRole("button", { name: "Jump to 12:34" }));
    expect(fixture.client.getTab).toHaveBeenCalledWith(4);
    expect(fixture.client.sendTabMessage).toHaveBeenCalledWith(4, {
      type: "youtube/seek",
      requestId: "job-complete",
      tabId: 4,
      videoId: "aaaaaaaaaaa",
      seconds: 754
    });

    (fixture.client.getTab as ReturnType<typeof vi.fn>).mockResolvedValueOnce({
      id: 4,
      active: true,
      url: "https://www.youtube.com/watch?v=bbbbbbbbbbb"
    });
    await userEvent.click(screen.getByRole("button", { name: "Jump to 12:34" }));
    expect(fixture.client.sendTabMessage).toHaveBeenCalledTimes(1);

    (fixture.client.getTab as ReturnType<typeof vi.fn>).mockResolvedValueOnce({
      id: 4,
      active: false,
      url: "https://www.youtube.com/watch?v=aaaaaaaaaaa"
    });
    await userEvent.click(screen.getByRole("button", { name: "Jump to 12:34" }));
    expect(fixture.client.sendTabMessage).toHaveBeenCalledTimes(1);
  });
});
