import type { CaptionTrack, TranscriptPreference } from "../domain/video";

function primaryLanguage(languageCode: string): string {
  return languageCode.split("-")[0]?.toLocaleLowerCase("en-US") ?? "";
}

function matchesLanguage(track: CaptionTrack, languageCode: string): boolean {
  return primaryLanguage(track.languageCode) === primaryLanguage(languageCode);
}

export function selectCaptionTrack(
  tracks: CaptionTrack[],
  preference: TranscriptPreference
): CaptionTrack | undefined {
  const priorities: Array<(track: CaptionTrack) => boolean> = [];

  if (preference.preferredLanguage !== null) {
    const preferredLanguage = preference.preferredLanguage;
    priorities.push(
      (track) => !track.isAutoGenerated && matchesLanguage(track, preferredLanguage),
      (track) => track.isAutoGenerated && matchesLanguage(track, preferredLanguage)
    );
  }

  priorities.push(
    (track) => !track.isAutoGenerated && matchesLanguage(track, preference.browserLanguage),
    (track) => track.isAutoGenerated && matchesLanguage(track, preference.browserLanguage),
    (track) => !track.isAutoGenerated,
    (track) => track.isAutoGenerated
  );

  for (const matchesPriority of priorities) {
    const match = tracks.find(matchesPriority);
    if (match !== undefined) return match;
  }

  return undefined;
}
