import { AppError } from "../domain/errors";
import type {
  CaptionTrack,
  Transcript,
  TranscriptPreference,
  TranscriptSegment,
  VideoContext
} from "../domain/video";
import { selectCaptionTrack } from "./captionSelection";
import { normalizeTranscript } from "./normalizeTranscript";
import { parseTimedText } from "./timedText";

export type TranscriptDependencies = {
  fetchText: (url: string, signal: AbortSignal) => Promise<string>;
  readVisibleSegments: (
    expectedVideoId: string,
    signal: AbortSignal
  ) => TranscriptSegment[] | Promise<TranscriptSegment[]>;
};

function unavailableError(): AppError {
  return new AppError({
    code: "captions_unavailable",
    retryable: false,
    safeMessage: "No YouTube transcript is available for this video.",
    recoveryAction: "none"
  });
}

function extractionError(cause: unknown): AppError {
  return new AppError({
    code: "transcript_extraction_failed",
    retryable: true,
    safeMessage: "The transcript could not be extracted.",
    recoveryAction: "retry",
    ...(cause instanceof Error ? { cause } : {})
  });
}

function isAbortError(error: unknown): boolean {
  return error instanceof DOMException && error.name === "AbortError" ||
    error instanceof Error && error.name === "AbortError";
}

function visibleTrack(preference: TranscriptPreference): CaptionTrack {
  return {
    id: "visible-transcript",
    languageCode: preference.preferredLanguage ?? preference.browserLanguage,
    label: "YouTube transcript",
    isAutoGenerated: false,
    baseUrl: ""
  };
}

export async function extractTranscript(
  context: VideoContext,
  preference: TranscriptPreference,
  dependencies: TranscriptDependencies,
  signal: AbortSignal
): Promise<Transcript> {
  signal.throwIfAborted();
  const track = selectCaptionTrack(context.captionTracks, preference);
  let captionFetchFailure: { cause: unknown } | null = null;

  if (track !== undefined) {
    try {
      const xml = await dependencies.fetchText(track.baseUrl, signal);
      signal.throwIfAborted();
      const segments = normalizeTranscript(parseTimedText(xml));
      if (segments.length > 0) return { track, segments };
      captionFetchFailure = {
        cause: new Error("YouTube returned no usable timed-text segments for an advertised track.")
      };
    } catch (error) {
      if (isAbortError(error) || signal.aborted) throw error;
      captionFetchFailure = { cause: error };
    }
  }

  try {
    signal.throwIfAborted();
    const segments = normalizeTranscript(await dependencies.readVisibleSegments(
      context.videoId,
      signal
    ));
    if (segments.length > 0) return { track: visibleTrack(preference), segments };
  } catch (error) {
    if (isAbortError(error) || signal.aborted) throw error;
    throw extractionError(error);
  }

  if (captionFetchFailure !== null) throw extractionError(captionFetchFailure.cause);
  throw unavailableError();
}
