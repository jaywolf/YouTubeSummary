import { z } from "zod";

export const captionTrackSchema = z.object({
  id: z.string().min(1),
  languageCode: z.string().min(1),
  label: z.string(),
  isAutoGenerated: z.boolean(),
  baseUrl: z.string()
}).strict();

export type CaptionTrack = z.infer<typeof captionTrackSchema>;

export const transcriptSegmentSchema = z.object({
  startSeconds: z.number().finite().nonnegative(),
  durationSeconds: z.number().finite().nonnegative(),
  text: z.string()
}).strict();

export type TranscriptSegment = z.infer<typeof transcriptSegmentSchema>;

export const transcriptSchema = z.object({
  track: captionTrackSchema,
  segments: z.array(transcriptSegmentSchema)
}).strict();

export type Transcript = z.infer<typeof transcriptSchema>;

export const transcriptPreferenceSchema = z.object({
  preferredLanguage: z.string().min(1).nullable(),
  browserLanguage: z.string().min(1)
}).strict();

export type TranscriptPreference = z.infer<typeof transcriptPreferenceSchema>;

export const videoContextSchema = z.object({
  videoId: z.string().regex(/^[A-Za-z0-9_-]{11}$/),
  canonicalUrl: z.url(),
  title: z.string(),
  channel: z.string().nullable(),
  durationSeconds: z.number().finite().nonnegative().nullable(),
  captionTracks: z.array(captionTrackSchema)
}).strict().superRefine((context, refinement) => {
  const identity = parseWatchUrl(context.canonicalUrl);
  if (identity?.videoId !== context.videoId) {
    refinement.addIssue({
      code: "custom",
      path: ["canonicalUrl"],
      message: "Canonical URL does not match video ID"
    });
  }
});

export type VideoContext = z.infer<typeof videoContextSchema>;

export function parseWatchUrl(
  value: string
): Pick<VideoContext, "videoId" | "canonicalUrl"> | null {
  try {
    const url = new URL(value);
    if (url.origin !== "https://www.youtube.com" || url.pathname !== "/watch") {
      return null;
    }

    const videoId = url.searchParams.get("v");
    if (!videoId || !/^[A-Za-z0-9_-]{11}$/.test(videoId)) return null;

    return {
      videoId,
      canonicalUrl: `https://www.youtube.com/watch?v=${videoId}`
    };
  } catch {
    return null;
  }
}
