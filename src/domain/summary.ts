import { z } from "zod";

export const SUMMARY_SCHEMA_VERSION = 1 as const;
export const SUMMARY_LIMITATION = "Generated from captions." as const;

const noControlCharacters = /^[^\u0000-\u001f\u007f-\u009f]*$/u;

function plainText(maxLength: number) {
  return z.string()
    .min(1)
    .max(maxLength)
    .regex(noControlCharacters, "Control characters are not allowed");
}

const timestampSchema = z.number().finite().nonnegative();
const optionalTimestampSchema = timestampSchema.optional();
const isoDateTimeSchema = z.string().datetime({ offset: true });

export const takeawaySchema = z.object({
  text: plainText(1_000),
  startSeconds: optionalTimestampSchema
}).strict();

export const summarySectionSchema = z.object({
  heading: plainText(300),
  startSeconds: timestampSchema,
  paragraphs: z.array(plainText(3_000)).min(1).max(8)
}).strict();

export const summaryContentSchema = z.object({
  overview: z.array(plainText(2_000)).min(1).max(4),
  takeaways: z.array(takeawaySchema).min(1).max(12),
  sections: z.array(summarySectionSchema).min(1).max(30)
}).strict();

export type SummaryContent = z.infer<typeof summaryContentSchema>;

export const videoSummarySchema = summaryContentSchema.extend({
  schemaVersion: z.literal(SUMMARY_SCHEMA_VERSION),
  limitation: z.literal(SUMMARY_LIMITATION),
  generatedAt: isoDateTimeSchema
}).strict();

export type VideoSummary = z.infer<typeof videoSummarySchema>;

export const chunkFactSchema = z.object({
  text: plainText(1_000),
  startSeconds: timestampSchema
}).strict();

export const chunkSectionStartSchema = z.object({
  heading: plainText(300),
  startSeconds: timestampSchema
}).strict();

export const chunkSummarySchema = z.object({
  facts: z.array(chunkFactSchema).min(1).max(50),
  sectionStarts: z.array(chunkSectionStartSchema).max(30)
}).strict();

export type ChunkSummary = z.infer<typeof chunkSummarySchema>;

export const completedSummaryPayloadSchema = z.object({
  video: z.object({
    videoId: z.string().regex(/^[A-Za-z0-9_-]{11}$/),
    title: plainText(500),
    channel: plainText(300).nullable()
  }).strict(),
  caption: z.object({
    languageCode: plainText(100),
    label: plainText(200),
    isAutoGenerated: z.boolean()
  }).strict(),
  summary: videoSummarySchema,
  cache: z.object({
    key: plainText(1_000),
    createdAt: isoDateTimeSchema
  }).strict().nullable()
}).strict();

export type CompletedSummaryPayload = z.infer<typeof completedSummaryPayloadSchema>;
